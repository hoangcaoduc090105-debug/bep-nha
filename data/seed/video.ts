/**
 * Marks the steps whose part of the video does not say an amount the step uses — the channel
 * gave it earlier, or only in the description — so the screen can point at "Cần dùng" instead.
 */
const markSilentSteps = (seed: Seed): Seed => ({
  ...seed,
  steps: seed.steps.map((step) => {
    const silent = step.uses.some(({ slot }) => {
      const source = seed.ingredients.find((i) => i.slot === slot)?.amountSource;
      if (!source) return false;
      return source === "description" || source.saidFrom < step.videoStartSeconds! || source.saidTo > step.videoEndSeconds!;
    });
    return silent ? { ...step, videoOmitsAmounts: true } : step;
  }),
});

export const VIDEO_SEEDS: Seed[] = DISHES.map(markSilentSteps);
