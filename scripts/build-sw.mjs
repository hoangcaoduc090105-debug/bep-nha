// Runs after `next build`. Writes out/sw.js: a service worker that stores every file of the
// built site on the device, so the app opens and works with no network at all.
// The list of files and a version derived from their contents are baked in, so a new
// deployment is picked up as a new version.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(OUT)
  .map((p) => relative(OUT, p).split(sep).join("/"))
  .filter((p) => p !== "sw.js" && p !== ".nojekyll")
  .sort();

const hash = createHash("sha256");
for (const f of files) hash.update(f).update(readFileSync(join(OUT, f)));
const version = hash.digest("hex").slice(0, 12);
const urls = files.map((f) => `${base}/${encodeURI(f)}`);

const sw = `// GENERATED by scripts/build-sw.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(base)};
const CACHE = "bep-nha-" + VERSION;
const FILES = ${JSON.stringify(urls)};
// Cover pictures of the videos some dishes are rewritten from. Kept across versions of the app,
// so a dish she has seen once still shows its picture with no network.
const COVERS = "anh-bia-video";
const COVER_HOST = "https://i.ytimg.com";

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

// A new version waits until the app has been closed, so one visit never mixes two versions.
// The page can ask it to take over at once ("Cập nhật").
self.addEventListener("message", (event) => {
  if (event.data === "skip-waiting") self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key.startsWith("bep-nha-") && key !== CACHE) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  // HEAD is how the app asks "does this page exist?" before moving to it; it must also be
  // answered from the device, or the question fails when there is no network.
  if (request.method !== "GET" && request.method !== "HEAD") return;
  const url = new URL(request.url);
  if (url.origin === COVER_HOST && request.method === "GET") {
    event.respondWith(
      (async () => {
        const covers = await caches.open(COVERS);
        const kept = await covers.match(url.href);
        if (kept) return kept;
        try {
          const fresh = await fetch(request);
          if (fresh.ok) await covers.put(url.href, fresh.clone());
          return fresh;
        } catch {
          return Response.error(); // no network: the page shows its "Chưa có ảnh" tile
        }
      })(),
    );
    return;
  }
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + "/")) return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      // Recipe pages differ only by ?id=…, so the query string is ignored when matching.
      // Matching is done by address (a stored page answers both GET and HEAD).
      let hit = await cache.match(url.href, { ignoreSearch: true });
      if (!hit && (request.mode === "navigate" || request.method === "HEAD")) {
        const dir = url.pathname.endsWith("/") ? url.pathname : url.pathname + "/";
        hit = await cache.match(dir + "index.html");
      }
      if (hit) return request.method === "HEAD" ? new Response(null, { status: 200, headers: hit.headers }) : hit;
      try {
        return await fetch(request);
      } catch {
        if (request.mode === "navigate") return (await cache.match(BASE + "/index.html")) ?? Response.error();
        return Response.error();
      }
    })(),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
const bytes = files.reduce((n, f) => n + statSync(join(OUT, f)).size, 0);
console.log(`sw.js: version ${version}, ${files.length} files, ${(bytes / 1024 / 1024).toFixed(1)} MB stored for offline use`);
